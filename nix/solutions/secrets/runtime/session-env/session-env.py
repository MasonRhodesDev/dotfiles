import json
import os
import re
import selectors
import shlex
import subprocess
import sys
import time

OUT = os.path.expanduser("~/.config/dotfiles/env.sh")
KEYS = "__DOTFILES_KEYS"
DENY = {"PATH", "HOME", "USER", "SHELL", "BASH_ENV", "ENV", "IFS", "PS1", "PS2",
        "PROMPT_COMMAND", "LD_PRELOAD", "LD_LIBRARY_PATH", "PWD", "OLDPWD", KEYS}
VALID_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def log(msg):
    print(msg, file=sys.stderr, flush=True)


def usable(env):
    return {k: v for k, v in env.items() if isinstance(k, str) and isinstance(v, str) and VALID_KEY.match(k) and k not in DENY}


def declared(credential, wanted):
    values, missing = {}, []
    for name, variable in sorted(wanted.items()):
        done = subprocess.run([credential, "get", name], stdin=subprocess.DEVNULL, capture_output=True, text=True)
        if done.returncode == 0 and done.stdout:
            values[variable] = done.stdout
        else:
            missing.append(name)
    return values, missing


def render(env):
    lines = ["# Generated by dotfiles-session-env. Do not edit; changes are overwritten."]
    lines += [f"export {k}={shlex.quote(v)}" for k, v in sorted(env.items())]
    lines.append(f"{KEYS}={shlex.quote(' '.join(sorted(env)))}")
    return "\n".join(lines) + "\n"


def write_if_changed(content):
    try:
        with open(OUT) as f:
            if f.read() == content:
                return False
    except FileNotFoundError:
        pass
    os.makedirs(os.path.dirname(OUT), mode=0o700, exist_ok=True)
    tmp = OUT + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(content)
    os.chmod(tmp, 0o600)
    os.replace(tmp, OUT)
    return True


def publish(env, before):
    gone = sorted(set(before) - set(env))
    if env:
        subprocess.run(["systemctl", "--user", "import-environment", *sorted(env)], env={**os.environ, **env}, check=False)
    if gone:
        subprocess.run(["systemctl", "--user", "unset-environment", *gone], check=False)


class Source:
    def __init__(self, program, selector):
        self.program, self.selector, self.child, self.env, self.retry = program, selector, None, {}, 0.0

    def start(self, now):
        if self.program == "-" or self.child or now < self.retry:
            return
        self.child = subprocess.Popen([self.program], stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, text=True)
        self.selector.register(self.child.stdout, selectors.EVENT_READ, self)

    def read(self, now, interval):
        line = self.child.stdout.readline()
        if line:
            try:
                given = json.loads(line)
            except ValueError:
                log("the provider's env project sent something other than JSON; keeping what it sent before")
                return False
            if isinstance(given, dict):
                self.env = usable(given)
                return True
            return False
        self.selector.unregister(self.child.stdout)
        self.child.stdout.close()
        self.child.wait()
        self.child, self.retry = None, now + interval
        return False


def main(argv):
    source_program, credential, wanted_path, mode = argv
    with open(wanted_path) as f:
        wanted = json.load(f)
    interval = float(os.environ.get("DOTFILES_SESSION_INTERVAL", "120"))
    selector = selectors.DefaultSelector()
    source = Source(source_program, selector)
    values, said, published, next_resolve = {}, None, {}, 0.0
    while True:
        now = time.monotonic()
        source.start(now)
        if now >= next_resolve:
            values, missing = declared(credential, wanted)
            next_resolve = now + interval
            status = f"{len(values)} declared session credentials" + (f"; unavailable: {' '.join(missing)}" if missing else "")
            if status != said:
                log(status)
                said = status
        env = {**source.env, **usable(values)}
        if write_if_changed(render(env)):
            log(f"env.sh updated ({len(env)} keys)")
            if mode == "import":
                publish(env, published)
                published = env
        wait = max(0.0, next_resolve - time.monotonic())
        if source.child is None and source.program != "-":
            wait = min(wait, max(0.0, source.retry - time.monotonic()))
        for key, _ in selector.select(wait):
            key.data.read(time.monotonic(), interval)


if __name__ == "__main__":
    main(sys.argv[1:])
